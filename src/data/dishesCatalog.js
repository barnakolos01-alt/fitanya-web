export function searchDishes(searchTerm) {
  if (!searchTerm || searchTerm.trim().length < 2) return [];
  const cleanTerms = searchTerm
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .trim()
    .split(/\s+/);

  const scored = DISHES_CATALOG.map((dish) => {
    const nameNorm = dish.name
      .toLowerCase()
      .normalize("NFD")
      .replace(/[\u0300-\u036f]/g, "");

    let score = 0;
    const fullClean = cleanTerms.join(" ");

    if (nameNorm.startsWith(fullClean)) {
      score += 100;
    } else if (nameNorm.includes(fullClean)) {
      score += 50;
    }

    let matchedWords = 0;
    cleanTerms.forEach((term) => {
      if (nameNorm.includes(term)) {
        matchedWords++;
        score += 15;
      } else {
        const matchKeyword = dish.keywords.some((kw) => {
          const kwNorm = kw
            .toLowerCase()
            .normalize("NFD")
            .replace(/[\u0300-\u036f]/g, "");
          return kwNorm.includes(term);
        });
        if (matchKeyword) {
          matchedWords++;
          score += 10;
        }
      }
    });

    if (matchedWords === 0) {
      score = 0;
    } else if (matchedWords === cleanTerms.length && cleanTerms.length > 1) {
      score += 20;
    }

    return { dish, score };
  });

  return scored
    .filter((item) => item.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, 7)
    .map((item) => item.dish);
}
